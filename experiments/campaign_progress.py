"""
campaign_progress.py — a progress report of the running research-plan
campaign, written from the machine's own state (process table, logs, result
records), so that progress can be checked independently on GitHub.
Writes docs/CAMPAIGN_PROGRESS.md.
"""

import os, re, json, glob, subprocess, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOG = os.path.join(ROOT, "results", "logs", "completion_master.log")
now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
log = open(LOG).read().splitlines() if os.path.exists(LOG) else []
since = max((i for i, l in enumerate(log) if l.startswith("RESTART")), default=0)
done = [l[7:] for l in log[since:] if l.startswith("done")]
failed = [l[7:] for l in log[since:] if l.startswith("FAILED")]
stages = [l for l in log if l.startswith("STAGE")]
load = open("/proc/loadavg").read().split()[:3]
ps = subprocess.run(["ps", "-eo", "etime,pcpu,cmd"], capture_output=True, text=True).stdout.splitlines()
jobs = [l.strip() for l in ps if re.search(r"experiments/(campaign_|crosscheck|cfd_)", l)]
foam = [l.strip() for l in ps if "Foam" in l]
recs = []
for f in sorted(glob.glob(os.path.join(ROOT, "results", "results_*.json")), key=os.path.getmtime)[-12:]:
    try:
        n = len(json.load(open(f)))
    except Exception:
        n = "?"
    t = datetime.datetime.fromtimestamp(os.path.getmtime(f), datetime.timezone.utc).strftime("%m-%d %H:%M")
    recs.append(f"| `{os.path.basename(f)}` | {n} | {t} |")
n_cfd = len(glob.glob(os.path.join(ROOT, "results", "cfd_runs", "*.json")))
out = [f"# Campaign progress ({now})", "",
       "Generated by `experiments/campaign_progress.py` from the machine's process table, the",
       "campaign log and the result records. The runs are those of `docs/RESEARCH_PLAN.md`.", "",
       f"- Load average (4 cores): {' '.join(load)}",
       f"- Jobs finished since the restart of 2026-10-19 08:00 UTC: {len(done)}; failed: {len(failed)}",
       f"- Cached CFD runs: {n_cfd}", "", "## Stages", ""] + [f"- {s}" for s in stages] + [
       "", "## Running now (elapsed time, CPU %, command)", ""] + [f"- `{j}`" for j in jobs + foam] + [
       "", "## Most recently written result records", "", "| File | Records (seeds) | Last written (UTC) |",
       "|---|---|---|"] + recs[::-1] + ["", "## Last 15 finished jobs", ""] + [f"- {d}" for d in done[-15:]] + [""]
open(os.path.join(ROOT, "docs", "CAMPAIGN_PROGRESS.md"), "w").write("\n".join(out))
print("\n".join(out[:12]))
